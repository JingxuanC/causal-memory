//! L0 active pinning — render the causal memory directory to a
//! `CAUSAL_MEMORY.md` file (default <200 lines) meant to be pinned into the
//! agent's system prompt, so the agent always knows what experience it holds
//! without spending a tool call (Claude Code MEMORY.md-style; the passive
//! `causal_directory` tool stays for on-demand refresh).
//!
//! The file is pointer-style: one line per entry, full detail left to
//! trace_cause / search_causal / intervention_query. Orchestration lives in
//! `Memory::build_pin_file` (ops.rs); this module is the pure renderer.

/// One renderable section of the pinned file. Empty sections are omitted.
pub struct PinSection {
    pub heading: String,
    pub lines: Vec<String>,
}

/// Header pinned at the top of the file. Tells the agent (and the human)
/// what this file is, that it is machine-generated, and how to refresh it.
pub fn header() -> &'static str {
    "# CAUSAL_MEMORY.md — causal memory directory (L0)\n\
     > Auto-generated by the `causal_pin` MCP tool — do not edit by hand;\n\
     > re-run `causal_pin` to refresh. Entries are one-line POINTERS:\n\
     > call trace_cause / search_causal / intervention_query with the\n\
     > decision text for full details."
}

/// Render sections into the pinned file, hard-capped at `max_lines` total.
/// When over budget, entries are dropped from the END (oldest entries of
/// the last sections first — recent decisions and do-not-retry warnings are
/// the most valuable and survive longest), and a one-line truncation note is
/// appended. Returns (content, truncated).
pub fn render_pin(sections: Vec<PinSection>, max_lines: usize) -> (String, bool) {
    let header_lines = header().lines().count();

    // Layout: header + per non-empty section (blank + heading + lines).
    let mut secs: Vec<(String, Vec<String>)> = sections
        .into_iter()
        .filter(|s| !s.lines.is_empty())
        .map(|s| (s.heading, s.lines))
        .collect();
    let mut total = header_lines
        + secs
            .iter()
            .map(|(_, l)| l.len() + 2) // blank + heading
            .sum::<usize>();

    let mut dropped = 0usize;
    let mut truncated = false;
    // Reserve one line for the truncation note whenever we need to cut.
    let budget = max_lines.saturating_sub(1);
    while total > budget {
        truncated = true;
        // Find the last section that still has lines.
        if let Some((_, lines)) = secs.iter_mut().rev().find(|(_, l)| !l.is_empty()) {
            lines.pop();
            dropped += 1;
            total -= 1;
            // Section emptied → its blank + heading go too.
            if lines.is_empty() {
                total -= 2;
            }
        } else {
            // Nothing left to cut (all sections gone) — give up trimming.
            break;
        }
    }

    let mut lines: Vec<String> = header().lines().map(|s| s.to_string()).collect();
    for (heading, sec_lines) in &secs {
        if sec_lines.is_empty() {
            continue;
        }
        if lines.last().map(|l| !l.is_empty()).unwrap_or(false) {
            lines.push(String::new()); // single blank line separator
        }
        lines.push(heading.clone());
        lines.extend(sec_lines.iter().cloned());
    }
    if truncated {
        lines.push(format!(
            "> … truncated: {dropped} pointer(s) dropped (older / lower sections omitted); re-run causal_pin with a higher max_lines to see all."
        ));
    }
    // Pathological max_lines smaller than the header: still honor the cap.
    let capped: Vec<String> = lines.into_iter().take(max_lines).collect();
    (capped.join("\n"), truncated)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::memory::Memory;

    fn sec(heading: &str, n: usize) -> PinSection {
        PinSection {
            heading: heading.to_string(),
            lines: (1..=n).map(|i| format!("- line {i}")).collect(),
        }
    }

    #[test]
    fn under_budget_renders_everything() {
        let (out, truncated) = render_pin(vec![sec("## A", 3), sec("## B", 2)], 200);
        assert!(!truncated);
        assert_eq!(out.lines().count(), 5 + (1 + 1 + 3) + (1 + 1 + 2));
        assert!(out.contains("## A"));
        assert!(out.contains("## B"));
        assert!(out.contains("- line 3"));
        assert!(!out.contains("truncated"));
    }

    #[test]
    fn empty_sections_are_omitted() {
        let (out, truncated) = render_pin(vec![sec("## A", 0), sec("## B", 1)], 200);
        assert!(!truncated);
        assert!(!out.contains("## A"));
        assert!(out.contains("## B"));
    }

    #[test]
    fn over_budget_drops_from_the_end_and_notes_it() {
        // header(5) + A(2+3) + B(2+3) = 15 lines; cap at 10 → cut 5+note.
        let (out, truncated) = render_pin(vec![sec("## A", 3), sec("## B", 3)], 10);
        assert!(truncated);
        assert!(out.lines().count() <= 10, "got {}", out.lines().count());
        assert!(out.contains("truncated"), "{out}");
        // First section survives; the last one is cut entirely.
        assert!(out.contains("## A"), "{out}");
        assert!(!out.contains("## B"), "{out}");
    }

    #[test]
    fn tiny_budget_still_honors_the_cap() {
        let (out, _) = render_pin(vec![sec("## A", 10)], 3);
        assert!(out.lines().count() <= 3);
    }

    #[test]
    fn header_present_and_points_at_tools() {
        let (out, _) = render_pin(vec![], 200);
        assert!(out.contains("# CAUSAL_MEMORY.md"));
        assert!(out.contains("causal_pin"));
        assert!(out.contains("trace_cause"));
    }

    #[test]
    fn build_pin_file_sections_and_cap() {
        let memory = Memory::open_in_memory().unwrap();
        assert!(memory
            .record_decision(
                "used global lock for cache",
                "deadlock under load",
                "caused",
                "locking",
                Some("rule"),
                None,
                None,
            )
            .starts_with("✅"));
        assert!(memory
            .record_decision(
                "sharded locks per key range",
                "contention resolved",
                "caused",
                "locking",
                Some("rule"),
                None,
                None,
            )
            .starts_with("✅"));
        // Explicitly invalidate the first edge (don't rely on contradiction
        // auto-invalidation heuristics).
        let edge_id: i64 = memory
            .store()
            .with_conn(|conn| {
                conn.query_row(
                    "SELECT ce.id FROM causal_edges ce
                     JOIN chunks cf ON cf.id = ce.from_id
                     WHERE cf.text = 'used global lock for cache'
                     ORDER BY ce.event_time LIMIT 1",
                    [],
                    |row| row.get(0),
                )
                .map_err(|e| anyhow::anyhow!("lookup: {e}"))
            })
            .unwrap();
        assert!(memory
            .invalidate_decision(edge_id, Some("test"))
            .starts_with("✅"));

        let full = memory.build_pin_file(20, 200);
        assert!(full.contains("# CAUSAL_MEMORY.md"), "{full}");
        assert!(full.contains("trace_cause"), "{full}");
        assert!(full.contains("## Recent decisions"), "{full}");
        assert!(full.contains("do NOT retry"), "{full}");
        assert!(full.contains("sharded locks per key range"), "{full}");
        // The invalidated first edge shows up struck-through in warnings and
        // is excluded from the recent-decisions index.
        assert!(
            full.contains("~~[locking] used global lock for cache~~"),
            "{full}"
        );
        let capped = memory.build_pin_file(20, 10);
        assert!(
            capped.lines().count() <= 10,
            "cap honored, got {}",
            capped.lines().count()
        );
        assert!(capped.contains("truncated"), "{capped}");
    }

    #[test]
    fn invalidated_edges_never_resurface_as_live_pointers() {
        // Regression: with more invalidated edges than the do-not-retry
        // section's own limit, an old invalidated edge must NOT reappear in
        // the recent-decisions index (do-NOT-retry rendered as a live pointer
        // is the worst possible pin output). The exclusion must be SQL-layer,
        // not capped by the invalidations list.
        let memory = Memory::open_in_memory().unwrap();
        let mut edge_ids = Vec::new();
        for i in 0..12 {
            assert!(memory
                .record_decision(
                    &format!("decision number {i}"),
                    &format!("outcome number {i}"),
                    "caused",
                    "regression",
                    Some("rule"),
                    None,
                    None,
                )
                .starts_with("✅"));
            let id: i64 = memory
                .store()
                .with_conn(|conn| {
                    conn.query_row(
                        "SELECT ce.id FROM causal_edges ce
                         JOIN chunks cf ON cf.id = ce.from_id
                         WHERE cf.text = ?1",
                        [&format!("decision number {i}")],
                        |row| row.get(0),
                    )
                    .map_err(|e| anyhow::anyhow!("lookup: {e}"))
                })
                .unwrap();
            edge_ids.push(id);
        }
        // Invalidate all but the last decision (> any reasonable list cap).
        for id in &edge_ids[..11] {
            assert!(memory
                .invalidate_decision(*id, Some("regression"))
                .starts_with("✅"));
        }

        let pin = memory.build_pin_file(20, 200);
        // The one valid decision is the only live pointer.
        assert!(pin.contains("decision number 11"), "{pin}");
        for i in 0..11 {
            // Every invalidated decision appears ONLY struck-through.
            let live = format!("- [regression] decision number {i} →");
            assert!(
                !pin.contains(&live),
                "invalidated edge {i} resurfaced: {pin}"
            );
            let struck = format!("~~[regression] decision number {i}~~");
            assert!(
                pin.contains(&struck),
                "invalidated edge {i} missing warning: {pin}"
            );
        }
    }

    #[test]
    fn build_pin_file_empty_store() {
        let memory = Memory::open_in_memory().unwrap();
        let out = memory.build_pin_file(20, 200);
        assert!(out.contains("# CAUSAL_MEMORY.md"), "{out}");
        assert!(out.contains("no decisions recorded yet"), "{out}");
    }
}
